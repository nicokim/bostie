from enum import KEEP, Enum, IntEnum, IntFlag, StrEnum
from typing import Self, override

_FLAG_WIDTH = 128
_MSGSPEC_ENUM_MAX = (1 << 63) - 1


def _named_unknown[E: Enum](cls: type[E], unknown: E, value: int | str) -> E:
    unknown._name_ = f"UNKNOWN_{value}"
    unknown._value_ = value
    cls._value2member_map_.setdefault(value, unknown)
    return cls(value)


class DiscordIntEnum(IntEnum):
    """An IntEnum that maps unknown values to stable `UNKNOWN_<value>` members."""

    @classmethod
    @override
    def _missing_(cls, value: object) -> Self | None:
        if not isinstance(value, int):
            return None
        return _named_unknown(cls, int.__new__(cls, value), value)


class DiscordIntFlag(IntFlag, boundary=KEEP):
    """An IntFlag whose operators, `~` included, keep bits bostie does not know."""

    @classmethod
    @override
    def _missing_(cls, value: object) -> Self:
        if isinstance(value, int):
            if value < 0:
                return cls(value & ((1 << _FLAG_WIDTH) - 1))
            known = cls._value2member_map_.get(value)
            if isinstance(known, cls):
                return known
        flag: Self = super()._missing_(value)
        if flag > _MSGSPEC_ENUM_MAX:
            cls._value2member_map_.pop(value, None)
        return flag


class DiscordStrEnum(StrEnum):
    """A StrEnum that maps unknown values to stable `UNKNOWN_<value>` members."""

    @classmethod
    @override
    def _missing_(cls, value: object) -> Self | None:
        if not isinstance(value, str):
            return None
        return _named_unknown(cls, str.__new__(cls, value), value)


